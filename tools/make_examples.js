// Generate synthetic example files (no participant data):  node tools/make_examples.js
'use strict';
const fs = require('fs'), path = require('path');
const C = require('../web/js/core.js');
const OUT = path.join(__dirname, '..', 'examples');

// 1. A synthetic session exercising the workflow. Fixed ids so the file is reproducible in content.
const s = C.newSession({ sessionId: 'synthetic-example-0001', participant: 'SYNTH-01', condition: 'synthetic-demo' });
s.notes = 'Synthetic example generated by tools/make_examples.js. Not participant data.';
C.recordGalleryOutcome(s, 'more-than-one', {});
const combo = C.combine(s, 'bend', 'hole');
C.chooseCandidate(s, combo.id, 'p1');
C.togglePin(s, 'holeSize');
const alt = C.requestAlternatives(s, { seed: 20261102 });
C.chooseCandidate(s, alt.id, 'p0');
C.setParam(s, 'bendSpacing', 1.1, { source: 'mouse', coalesce: 'slider:bendSpacing' });
C.endCoalesce(s);
const alt2 = C.requestAlternatives(s, { repeat: true, seed: 20261103 });
C.chooseCandidate(s, alt2.id, 'keep');
C.captureDescription(s, { text: 'SYNTHETIC: the gap looks a bit lower and the waves are slightly tighter at the top.', region: { x0: -0.4, y0: -0.8, x1: 0.4, y1: 0 }, properties: ['hole', 'bend'], aiStatus: 'AI off' });
C.accept(s, 'approximate');
C.setOutcome(s, 'approximate', 'synthetic');
fs.writeFileSync(path.join(OUT, 'synthetic-session.json'), JSON.stringify(s, null, 1));

// 2. The semantic gallery for the default reference, as reusable reconstructions.
const items = C.galleryItems(C.defaultReference()).filter((i) => i.kind !== 'legacy')
  .map((i) => ({ id: i.id, kind: i.kind, label: i.label, recon: i.recon }));
fs.writeFileSync(path.join(OUT, 'semantic-gallery.json'), JSON.stringify({ schema: 'distortion-lab/gallery/1', softwareVersion: C.VERSION,
  reference: C.defaultReference(), note: 'Deterministic illustrative appearances of the semantic generator; not validated percept categories.', items }, null, 1));
console.log('wrote examples/synthetic-session.json and examples/semantic-gallery.json');
