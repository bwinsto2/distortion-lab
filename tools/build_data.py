#!/usr/bin/env python3
"""Generate web/js/data.js from shared/*.json so the browser (including file://
preview mode) and the Python backend use exactly the same schema and presets.

Run:  python3 tools/build_data.py          (writes web/js/data.js)
      python3 tools/build_data.py --check  (exit 1 if web/js/data.js is stale)
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from distortion_lab import VERSION, SESSION_SCHEMA  # noqa: E402


def generate():
    with open(os.path.join(ROOT, "shared", "parameters.json"), encoding="utf-8") as f:
        params = json.load(f)
    with open(os.path.join(ROOT, "shared", "legacy-presets.json"), encoding="utf-8") as f:
        presets = json.load(f)
    data = {"version": VERSION, "sessionSchema": SESSION_SCHEMA,
            "parameters": params, "legacyPresets": presets}
    body = json.dumps(data, ensure_ascii=False, sort_keys=True, indent=1)
    return ("// GENERATED by tools/build_data.py from shared/*.json. Do not edit by hand.\n"
            "(function (root) {\n  var DATA = " + body + ";\n"
            "  if (typeof module === 'object' && module.exports) module.exports = DATA;\n"
            "  else root.DL_DATA = DATA;\n"
            "})(typeof self !== 'undefined' ? self : this);\n")


def main():
    out = os.path.join(ROOT, "web", "js", "data.js")
    text = generate()
    if "--check" in sys.argv:
        current = open(out, encoding="utf-8").read() if os.path.exists(out) else ""
        if current != text:
            print("web/js/data.js is stale; run python3 tools/build_data.py")
            sys.exit(1)
        print("web/js/data.js is up to date")
        return
    with open(out, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", os.path.relpath(out, ROOT))


if __name__ == "__main__":
    main()
